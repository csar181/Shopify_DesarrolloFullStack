-- ============================================================
-- SHOPCLOUD
-- Script de creación de base de datos para PostgreSQL
-- Modelo: multitenencia por tienda
-- ============================================================
-- Recomendación:
--   1. Crear una base de datos vacía llamada shopcloud.
--   2. Conectarse a ella.
--   3. Ejecutar este archivo completo.
--
-- Notas de implementación:
--   - Los importes se almacenan con NUMERIC, nunca FLOAT.
--   - Las contraseñas deben guardarse como hashes seguros.
--   - El backend debe recalcular carritos, descuentos e impuestos.
--   - La desactivación por vencimiento de suscripción requiere un
--     proceso programado en Spring Boot.
--   - Los comprobantes son simulados; no son comprobantes
--     electrónicos emitidos ante SUNAT.
-- ============================================================

BEGIN;

-- ============================================================
-- 1. USUARIOS
-- Propietarios de tiendas y futuros administradores de plataforma
-- ============================================================

CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    correo_electronico VARCHAR(150) NOT NULL,
    contrasena VARCHAR(255) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_usuarios_correo UNIQUE (correo_electronico)
);

-- ============================================================
-- 2. ROLES
-- Se conserva para permitir empleados en futuras versiones.
-- El propietario actual se identifica en tiendas.propietario_id.
-- ============================================================

CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL UNIQUE,
    descripcion VARCHAR(255)
);

-- ============================================================
-- 3. TIENDAS
-- Un propietario puede tener varias tiendas.
-- ============================================================

CREATE TABLE tiendas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    propietario_id BIGINT NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    slug VARCHAR(100) NOT NULL UNIQUE,
    descripcion TEXT,
    url_logo VARCHAR(500),
    url_banner VARCHAR(500),
    color_primario VARCHAR(20),
    correo_contacto VARCHAR(150),
    telefono_contacto VARCHAR(30),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_tiendas_propietario
        FOREIGN KEY (propietario_id)
        REFERENCES usuarios(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    -- Necesaria como clave candidata para relaciones compuestas.
    CONSTRAINT uq_tiendas_propietario_id UNIQUE (propietario_id, id)
);

CREATE INDEX idx_tiendas_propietario
    ON tiendas(propietario_id);

-- ============================================================
-- 4. MIEMBROS_TIENDA
-- Preparada para futuros empleados y colaboradores.
-- No es obligatorio registrar al propietario aquí.
-- ============================================================

CREATE TABLE miembros_tienda (
    tienda_id BIGINT NOT NULL,
    usuario_id BIGINT NOT NULL,
    rol_id BIGINT NOT NULL,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_miembros_tienda
        PRIMARY KEY (tienda_id, usuario_id),

    CONSTRAINT fk_miembros_tienda_tienda
        FOREIGN KEY (tienda_id)
        REFERENCES tiendas(id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_miembros_tienda_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES usuarios(id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_miembros_tienda_rol
        FOREIGN KEY (rol_id)
        REFERENCES roles(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

CREATE INDEX idx_miembros_tienda_usuario
    ON miembros_tienda(usuario_id);

CREATE INDEX idx_miembros_tienda_rol
    ON miembros_tienda(rol_id);

-- ============================================================
-- 5. PLANES
-- Los límites NULL pueden interpretarse como ilimitados,
-- siempre que esa sea la regla definida por el negocio.
-- ============================================================

CREATE TABLE planes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL UNIQUE,
    descripcion TEXT,
    precio NUMERIC(10,2) NOT NULL DEFAULT 0,
    periodicidad VARCHAR(20) NOT NULL DEFAULT 'MENSUAL',
    max_productos INTEGER,
    max_usuarios INTEGER,
    max_categorias INTEGER,
    max_imagenes_producto INTEGER,
    funcionalidades JSONB,
    activo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT ck_planes_precio
        CHECK (precio >= 0),

    CONSTRAINT ck_planes_periodicidad
        CHECK (periodicidad IN ('MENSUAL', 'ANUAL')),

    CONSTRAINT ck_planes_limites
        CHECK (
            (max_productos IS NULL OR max_productos >= 0)
            AND (max_usuarios IS NULL OR max_usuarios >= 0)
            AND (max_categorias IS NULL OR max_categorias >= 0)
            AND (max_imagenes_producto IS NULL OR max_imagenes_producto >= 0)
        )
);

-- ============================================================
-- 6. SUSCRIPCIONES
-- Una tienda puede conservar historial, pero solo debe tener
-- una suscripción ACTIVA a la vez.
-- ============================================================

CREATE TABLE suscripciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tienda_id BIGINT NOT NULL,
    plan_id BIGINT NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'ACTIVA',
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_suscripciones_tienda
        FOREIGN KEY (tienda_id)
        REFERENCES tiendas(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_suscripciones_plan
        FOREIGN KEY (plan_id)
        REFERENCES planes(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT ck_suscripciones_estado
        CHECK (estado IN ('ACTIVA', 'VENCIDA', 'CANCELADA', 'PENDIENTE')),

    CONSTRAINT ck_suscripciones_fechas
        CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

CREATE INDEX idx_suscripciones_tienda
    ON suscripciones(tienda_id);

CREATE INDEX idx_suscripciones_plan
    ON suscripciones(plan_id);

CREATE UNIQUE INDEX uq_suscripciones_tienda_activa
    ON suscripciones(tienda_id)
    WHERE estado = 'ACTIVA';

-- ============================================================
-- 7. CATEGORIAS
-- Categorías simples por tienda.
-- ============================================================

CREATE TABLE categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tienda_id BIGINT NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    descripcion TEXT,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_categorias_tienda
        FOREIGN KEY (tienda_id)
        REFERENCES tiendas(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT uq_categorias_tienda_nombre
        UNIQUE (tienda_id, nombre),

    CONSTRAINT uq_categorias_tienda_id
        UNIQUE (tienda_id, id)
);

-- ============================================================
-- 8. PRODUCTOS
-- El precio registrado incluye IGV.
-- ============================================================

CREATE TABLE productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tienda_id BIGINT NOT NULL,
    categoria_id BIGINT,
    nombre VARCHAR(150) NOT NULL,
    descripcion TEXT,
    sku VARCHAR(100),
    precio NUMERIC(12,2) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    destacado BOOLEAN NOT NULL DEFAULT FALSE,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_productos_tienda
        FOREIGN KEY (tienda_id)
        REFERENCES tiendas(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    -- Garantiza que la categoría pertenezca a la misma tienda.
    CONSTRAINT fk_productos_categoria_tienda
        FOREIGN KEY (tienda_id, categoria_id)
        REFERENCES categorias(tienda_id, id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT ck_productos_precio
        CHECK (precio >= 0),

    CONSTRAINT uq_productos_tienda_id
        UNIQUE (tienda_id, id),

    CONSTRAINT uq_productos_tienda_sku
        UNIQUE (tienda_id, sku)
);

CREATE INDEX idx_productos_tienda_categoria
    ON productos(tienda_id, categoria_id);

-- ============================================================
-- 9. IMAGENES_PRODUCTO
-- ============================================================

CREATE TABLE imagenes_producto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id BIGINT NOT NULL,
    url_imagen VARCHAR(500) NOT NULL,
    es_principal BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT fk_imagenes_producto_producto
        FOREIGN KEY (producto_id)
        REFERENCES productos(id)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

CREATE INDEX idx_imagenes_producto_producto
    ON imagenes_producto(producto_id);

-- Solo una imagen principal por producto.
CREATE UNIQUE INDEX uq_imagen_principal_producto
    ON imagenes_producto(producto_id)
    WHERE es_principal = TRUE;

-- ============================================================
-- 10. VARIANTES
-- Si precio es NULL, se utiliza el precio del producto.
-- ============================================================

CREATE TABLE variantes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id BIGINT NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    sku VARCHAR(100),
    precio NUMERIC(12,2),
    activo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_variantes_producto
        FOREIGN KEY (producto_id)
        REFERENCES productos(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT ck_variantes_precio
        CHECK (precio IS NULL OR precio >= 0),

    CONSTRAINT uq_variantes_producto_id
        UNIQUE (producto_id, id),

    CONSTRAINT uq_variantes_producto_sku
        UNIQUE (producto_id, sku)
);

-- ============================================================
-- 11. INVENTARIO
-- variante_id NULL: stock general del producto.
-- variante_id informado: stock de una variante.
-- ============================================================

CREATE TABLE inventario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tienda_id BIGINT NOT NULL,
    producto_id BIGINT NOT NULL,
    variante_id BIGINT,
    cantidad INTEGER NOT NULL DEFAULT 0,
    cantidad_minima INTEGER NOT NULL DEFAULT 0,
    actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_inventario_producto_tienda
        FOREIGN KEY (tienda_id, producto_id)
        REFERENCES productos(tienda_id, id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    -- Garantiza que la variante pertenezca al producto indicado.
    CONSTRAINT fk_inventario_variante_producto
        FOREIGN KEY (producto_id, variante_id)
        REFERENCES variantes(producto_id, id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT ck_inventario_cantidad
        CHECK (cantidad >= 0),

    CONSTRAINT ck_inventario_cantidad_minima
        CHECK (cantidad_minima >= 0)
);

-- Un único registro de stock general por producto.
CREATE UNIQUE INDEX uq_inventario_producto_general
    ON inventario(producto_id)
    WHERE variante_id IS NULL;

-- Un único registro de stock por variante.
CREATE UNIQUE INDEX uq_inventario_variante
    ON inventario(variante_id)
    WHERE variante_id IS NOT NULL;

CREATE INDEX idx_inventario_tienda_producto
    ON inventario(tienda_id, producto_id);

-- ============================================================
-- 12. CLIENTES
-- Cada cliente tiene una cuenta independiente por tienda.
-- El mismo correo puede registrarse en distintas tiendas.
-- ============================================================

CREATE TABLE clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tienda_id BIGINT NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    correo_electronico VARCHAR(150) NOT NULL,
    contrasena VARCHAR(255) NOT NULL,
    telefono VARCHAR(30),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_clientes_tienda
        FOREIGN KEY (tienda_id)
        REFERENCES tiendas(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT uq_cliente_tienda_correo
        UNIQUE (tienda_id, correo_electronico),

    CONSTRAINT uq_clientes_tienda_id
        UNIQUE (tienda_id, id)
);

-- ============================================================
-- 13. DIRECCIONES
-- ============================================================

CREATE TABLE direcciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tienda_id BIGINT NOT NULL,
    cliente_id BIGINT NOT NULL,
    linea_direccion VARCHAR(255) NOT NULL,
    ciudad VARCHAR(100) NOT NULL,
    distrito VARCHAR(100),
    departamento VARCHAR(100),
    codigo_postal VARCHAR(20),
    referencia VARCHAR(255),
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_direcciones_cliente_tienda
        FOREIGN KEY (tienda_id, cliente_id)
        REFERENCES clientes(tienda_id, id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT uq_direcciones_tienda_cliente_id
        UNIQUE (tienda_id, cliente_id, id)
);

CREATE INDEX idx_direcciones_tienda_cliente
    ON direcciones(tienda_id, cliente_id);

-- ============================================================
-- 14. DATOS_FACTURACION
-- Datos fiscales reutilizables del cliente.
-- Los datos usados en una compra se copian a pedidos.
-- ============================================================

CREATE TABLE datos_facturacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tienda_id BIGINT NOT NULL,
    cliente_id BIGINT NOT NULL,
    tipo_documento VARCHAR(20) NOT NULL,
    numero_documento VARCHAR(20) NOT NULL,
    nombre_razon_social VARCHAR(150) NOT NULL,
    direccion_fiscal VARCHAR(255),
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_facturacion_cliente_tienda
        FOREIGN KEY (tienda_id, cliente_id)
        REFERENCES clientes(tienda_id, id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT ck_facturacion_tipo_documento
        CHECK (tipo_documento IN ('DNI', 'RUC', 'CE', 'PASAPORTE', 'OTRO')),

    CONSTRAINT uq_facturacion_tienda_cliente_id
        UNIQUE (tienda_id, cliente_id, id)
);

CREATE INDEX idx_facturacion_tienda_cliente
    ON datos_facturacion(tienda_id, cliente_id);

-- ============================================================
-- 15. CARRITOS
-- El carrito se persiste al iniciar sesión.
-- El backend mantiene actualizado el total.
-- ============================================================

CREATE TABLE carritos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tienda_id BIGINT NOT NULL,
    cliente_id BIGINT NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'ACTIVO',
    total NUMERIC(12,2) NOT NULL DEFAULT 0,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_carritos_cliente_tienda
        FOREIGN KEY (tienda_id, cliente_id)
        REFERENCES clientes(tienda_id, id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT ck_carritos_estado
        CHECK (estado IN ('ACTIVO', 'CONVERTIDO', 'ABANDONADO')),

    CONSTRAINT ck_carritos_total
        CHECK (total >= 0),

    CONSTRAINT uq_carritos_tienda_id
        UNIQUE (tienda_id, id)
);

CREATE INDEX idx_carritos_tienda_cliente
    ON carritos(tienda_id, cliente_id);

-- Solo un carrito ACTIVO por cliente en cada tienda.
CREATE UNIQUE INDEX uq_carrito_activo_cliente_tienda
    ON carritos(tienda_id, cliente_id)
    WHERE estado = 'ACTIVO';

-- ============================================================
-- 16. ELEMENTOS_CARRITO
-- Los precios se guardan como referencia al momento de añadir
-- el producto. El backend debe validarlos al confirmar compra.
-- ============================================================

CREATE TABLE elementos_carrito (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tienda_id BIGINT NOT NULL,
    carrito_id BIGINT NOT NULL,
    producto_id BIGINT NOT NULL,
    variante_id BIGINT,
    cantidad INTEGER NOT NULL,
    precio_unitario NUMERIC(12,2) NOT NULL,

    CONSTRAINT fk_elementos_carrito_carrito_tienda
        FOREIGN KEY (tienda_id, carrito_id)
        REFERENCES carritos(tienda_id, id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT fk_elementos_carrito_producto_tienda
        FOREIGN KEY (tienda_id, producto_id)
        REFERENCES productos(tienda_id, id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_elementos_carrito_variante_producto
        FOREIGN KEY (producto_id, variante_id)
        REFERENCES variantes(producto_id, id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT ck_elementos_carrito_cantidad
        CHECK (cantidad > 0),

    CONSTRAINT ck_elementos_carrito_precio
        CHECK (precio_unitario >= 0)
);

CREATE INDEX idx_elementos_carrito_carrito
    ON elementos_carrito(carrito_id);

-- Evita duplicados para productos sin variante.
CREATE UNIQUE INDEX uq_elemento_carrito_producto_sin_variante
    ON elementos_carrito(carrito_id, producto_id)
    WHERE variante_id IS NULL;

-- Evita duplicados para una misma variante.
CREATE UNIQUE INDEX uq_elemento_carrito_variante
    ON elementos_carrito(carrito_id, variante_id)
    WHERE variante_id IS NOT NULL;

CREATE INDEX idx_elementos_carrito_producto
    ON elementos_carrito(tienda_id, producto_id);

-- ============================================================
-- 17. DESCUENTOS
-- Se aplican al total del pedido después de sumar productos.
-- tipo: PORCENTAJE o MONTO_FIJO.
-- ============================================================

CREATE TABLE descuentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tienda_id BIGINT NOT NULL,
    codigo VARCHAR(50) NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    valor NUMERIC(12,2) NOT NULL,
    fecha_inicio TIMESTAMP NOT NULL,
    fecha_fin TIMESTAMP NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_descuentos_tienda
        FOREIGN KEY (tienda_id)
        REFERENCES tiendas(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT ck_descuentos_tipo
        CHECK (tipo IN ('PORCENTAJE', 'MONTO_FIJO')),

    CONSTRAINT ck_descuentos_valor
        CHECK (
            valor > 0
            AND (tipo <> 'PORCENTAJE' OR valor <= 100)
        ),

    CONSTRAINT ck_descuentos_fechas
        CHECK (fecha_fin >= fecha_inicio),

    CONSTRAINT uq_descuentos_tienda_codigo
        UNIQUE (tienda_id, codigo),

    CONSTRAINT uq_descuentos_tienda_id
        UNIQUE (tienda_id, id)
);

-- ============================================================
-- 18. PEDIDOS
-- subtotal: suma de precios de productos, IGV incluido.
-- descuento: se resta del subtotal.
-- base_imponible e IGV se calculan sobre el total descontado.
-- Todos los productos se consideran gravados al 18%.
-- ============================================================

CREATE TABLE pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tienda_id BIGINT NOT NULL,
    cliente_id BIGINT NOT NULL,
    direccion_id BIGINT NOT NULL,
    descuento_id BIGINT,
    datos_facturacion_id BIGINT,

    estado VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE',

    subtotal NUMERIC(12,2) NOT NULL,
    monto_descuento NUMERIC(12,2) NOT NULL DEFAULT 0,
    base_imponible NUMERIC(12,2) NOT NULL,
    porcentaje_igv NUMERIC(5,2) NOT NULL DEFAULT 18.00,
    monto_igv NUMERIC(12,2) NOT NULL,
    total NUMERIC(12,2) NOT NULL,

    -- Fotografía de la dirección de envío.
    envio_linea_direccion VARCHAR(255) NOT NULL,
    envio_ciudad VARCHAR(100) NOT NULL,
    envio_distrito VARCHAR(100),
    envio_departamento VARCHAR(100),
    envio_codigo_postal VARCHAR(20),
    envio_referencia VARCHAR(255),

    -- Fotografía de los datos del descuento.
    codigo_descuento VARCHAR(50),
    tipo_descuento VARCHAR(20),
    valor_descuento NUMERIC(12,2),

    -- Fotografía de los datos del comprobante simulado.
    tipo_comprobante VARCHAR(20) NOT NULL DEFAULT 'BOLETA',
    tipo_documento VARCHAR(20),
    numero_documento VARCHAR(20),
    nombre_razon_social VARCHAR(150),
    direccion_fiscal VARCHAR(255),
    numero_comprobante VARCHAR(50),
    estado_comprobante VARCHAR(30) NOT NULL DEFAULT 'GENERADO',

    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_pedidos_cliente_tienda
        FOREIGN KEY (tienda_id, cliente_id)
        REFERENCES clientes(tienda_id, id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_pedidos_direccion_cliente
        FOREIGN KEY (tienda_id, cliente_id, direccion_id)
        REFERENCES direcciones(tienda_id, cliente_id, id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_pedidos_descuento_tienda
        FOREIGN KEY (tienda_id, descuento_id)
        REFERENCES descuentos(tienda_id, id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_pedidos_facturacion_cliente
        FOREIGN KEY (tienda_id, cliente_id, datos_facturacion_id)
        REFERENCES datos_facturacion(tienda_id, cliente_id, id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT ck_pedidos_estado
        CHECK (estado IN (
            'PENDIENTE',
            'CONFIRMADO',
            'PREPARANDO',
            'ENVIADO',
            'ENTREGADO',
            'CANCELADO'
        )),

    CONSTRAINT ck_pedidos_importes
        CHECK (
            subtotal >= 0
            AND monto_descuento >= 0
            AND monto_descuento <= subtotal
            AND base_imponible >= 0
            AND monto_igv >= 0
            AND total >= 0
        ),

    CONSTRAINT ck_pedidos_porcentaje_igv
        CHECK (porcentaje_igv = 18.00),

    CONSTRAINT ck_pedidos_total
        CHECK (total = subtotal - monto_descuento),

    CONSTRAINT ck_pedidos_base_imponible
        CHECK (base_imponible = ROUND(total / (1 + porcentaje_igv / 100), 2)),

    CONSTRAINT ck_pedidos_monto_igv
        CHECK (monto_igv = total - base_imponible),

    CONSTRAINT ck_pedidos_tipo_comprobante
        CHECK (tipo_comprobante IN ('BOLETA', 'FACTURA')),

    CONSTRAINT ck_pedidos_estado_comprobante
        CHECK (estado_comprobante IN ('GENERADO', 'ANULADO')),

    CONSTRAINT ck_pedidos_datos_comprobante
        CHECK (
            numero_documento IS NOT NULL
            AND nombre_razon_social IS NOT NULL
        ),

    CONSTRAINT uq_pedidos_tienda_id
        UNIQUE (tienda_id, id)
);

CREATE INDEX idx_pedidos_tienda_creado
    ON pedidos(tienda_id, creado_en);

CREATE INDEX idx_pedidos_tienda_estado
    ON pedidos(tienda_id, estado);

CREATE INDEX idx_pedidos_tienda_cliente
    ON pedidos(tienda_id, cliente_id);

CREATE INDEX idx_pedidos_tienda_descuento
    ON pedidos(tienda_id, descuento_id);

-- ============================================================
-- 19. ELEMENTOS_PEDIDO
-- Conserva una fotografía de los productos comprados.
-- Los datos históricos se mantienen aunque cambie el catálogo.
-- ============================================================

CREATE TABLE elementos_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tienda_id BIGINT NOT NULL,
    pedido_id BIGINT NOT NULL,
    producto_id BIGINT NOT NULL,
    variante_id BIGINT,
    nombre_producto VARCHAR(150) NOT NULL,
    nombre_variante VARCHAR(100),
    sku VARCHAR(100),
    cantidad INTEGER NOT NULL,
    precio_unitario NUMERIC(12,2) NOT NULL,
    subtotal NUMERIC(12,2) NOT NULL,

    CONSTRAINT fk_elementos_pedido_pedido_tienda
        FOREIGN KEY (tienda_id, pedido_id)
        REFERENCES pedidos(tienda_id, id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_elementos_pedido_producto_tienda
        FOREIGN KEY (tienda_id, producto_id)
        REFERENCES productos(tienda_id, id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_elementos_pedido_variante_producto
        FOREIGN KEY (producto_id, variante_id)
        REFERENCES variantes(producto_id, id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT ck_elementos_pedido_cantidad
        CHECK (cantidad > 0),

    CONSTRAINT ck_elementos_pedido_importes
        CHECK (
            precio_unitario >= 0
            AND subtotal >= 0
            AND subtotal = cantidad * precio_unitario
        )
);

CREATE INDEX idx_elementos_pedido_pedido
    ON elementos_pedido(pedido_id);

CREATE INDEX idx_elementos_pedido_producto
    ON elementos_pedido(tienda_id, producto_id);

-- ============================================================
-- 20. METODOS_PAGO
-- Cada tienda configura sus propios métodos e instrucciones.
-- ============================================================

CREATE TABLE metodos_pago (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tienda_id BIGINT NOT NULL,
    nombre VARCHAR(50) NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    instrucciones TEXT,
    datos_pago TEXT,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_metodos_pago_tienda
        FOREIGN KEY (tienda_id)
        REFERENCES tiendas(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT uq_metodos_pago_tienda_nombre
        UNIQUE (tienda_id, nombre),

    CONSTRAINT uq_metodos_pago_tienda_id
        UNIQUE (tienda_id, id)
);

-- ============================================================
-- 21. TRANSACCIONES
-- Una sola transacción por pedido.
-- El pago manual se registra como REALIZADA según la regla
-- funcional acordada para el proyecto.
-- ============================================================

CREATE TABLE transacciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tienda_id BIGINT NOT NULL,
    pedido_id BIGINT NOT NULL,
    metodo_pago_id BIGINT NOT NULL,
    monto NUMERIC(12,2) NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'REALIZADA',
    referencia_transaccion VARCHAR(100),
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_transacciones_pedido_tienda
        FOREIGN KEY (tienda_id, pedido_id)
        REFERENCES pedidos(tienda_id, id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_transacciones_metodo_pago_tienda
        FOREIGN KEY (tienda_id, metodo_pago_id)
        REFERENCES metodos_pago(tienda_id, id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT ck_transacciones_monto
        CHECK (monto >= 0),

    CONSTRAINT ck_transacciones_estado
        CHECK (estado IN ('REALIZADA', 'ANULADA')),

    CONSTRAINT uq_transacciones_pedido
        UNIQUE (pedido_id)
);

CREATE INDEX idx_transacciones_metodo_pago
    ON transacciones(metodo_pago_id);

